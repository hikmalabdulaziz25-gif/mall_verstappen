# Cuplikan materi: Teknik slice atau slicing digunakan untuk mengakses sekumpulan element/item | dari data sequence sesuai dengan index yang diinginkan. Data sequence | sendiri adalah klasifikasi tipe data yang berisi kumpulan data terurut atau | sekuensial. Yang termasuk dalam tipe data sequence adalah list, range, tuple, | dan string.

data = [10, 20, 30, 40, 50]
print(data[1:4])
print(data[:3])
print(data[3:])
print(data[::2])
