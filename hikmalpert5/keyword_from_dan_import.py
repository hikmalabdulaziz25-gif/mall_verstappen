# Sumber PDF: A.27.4. Keyword from dan import
# Praktik terpisah sesuai subbab dalam PDF.
# Cuplikan materi: Ada dua bentuk penerapan keyword import . Pertama, yaitu untuk meng- | import module, contohya seperti pada praktek di atas ( import calculate ). | Kedua, adalah mengkombinasikan keyword tersebut dengan keyword from | untuk meng-import langsung fungsi atau item lainnya dari suatu module. | Contoh:

from math import sqrt, pi
print(sqrt(49))
print(pi)
