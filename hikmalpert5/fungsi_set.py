# Sumber PDF: A.15.5. Fungsi set()
# Praktik terpisah sesuai subbab dalam PDF.
# Cuplikan materi: ◉ Konversi string ke set | String dibungkus menggunakan method set() menghasilkan data set berisi karakter string yang unik. | ◉ Konversi list ke set | Data list bisa diubah menjadi set dengan mudah dengan cara membungkusnya menggunakan fungsi set() . Isi | dari set adalah elemen unik list.

print(set("abcda"))
print(set(["a", "b", "c", "a"]))
print(set(("a", "b", "c", "a")))
print(set(range(1, 5)))
