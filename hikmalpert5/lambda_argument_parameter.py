# Cuplikan materi: Sama seperti fungsi, lambda bisa memiliki parameter baik itu jenisnya | parameter positional, optional, ataupun keyword argument. | Sebagai contoh, lihat perbandingan fungsi get_full_name1() dengan lambda | get_full_name2() pada kode berikut. Parameter di lambda dituliskan | diantara keyword lambda dan tanda titik 2 : . Jika ada lebih dari 1

